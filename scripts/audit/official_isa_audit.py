#!/usr/bin/env python3
"""官方 AMD ISA XML 位域审计——四方验证的第五环（可复跑工具）

数据源：tinygrad rdna4/rdna3 autogen（"autogenerated from AMD ISA XML"，
官方规范的机器可读直译，/home/yanli/work/9060xt/tinygrad）。

流程：
  1. tests/encoding_golden_gen.rs 的 push 行 → 编码器字序列（gen 管线，禁手打）
  2. llvm-mc 反汇编（选 mcpu：gfx1250 前瞻/gfx1100 FLAT 路径/gfx1200 主）
  3. 官方位域表提取 opcode → 反查官方 enum 名
  4. llvm-mc 助记符 vs 官方名规范化对照（已知改名/路径映射表内置）

判读：
  语义匹配  = 编码器与官方规范一致
  NAME-DIFF = 名字规范化缺陷（人工核 op 值——多为 GFX12 改名 max→max_num）
  UNMATCH   = 红旗（要么新 bug，要么官方 XML 未收录的历史形式——人工裁决）

运行：python3 scripts/audit/official_isa_audit.py
（前置：cargo test --release --features rocm --test encoding_golden_gen -- --nocapture）
"""
import subprocess, json, re, sys, os

TINYGRAD = "/home/yanli/work/9060xt/tinygrad"
LLVM_MC = "/opt/rocm/llvm/bin/llvm-mc"
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

sys.path.insert(0, TINYGRAD)

def load_tables():
    enc = json.load(open(f"{REPO}/target/official_enc.json")) if os.path.exists(f"{REPO}/target/official_enc.json") else None
    sys.path.insert(0, TINYGRAD)
    # 动态构建官方表（encoding 前缀 + op 位域 + 枚举名值表）
    from tinygrad.runtime.autogen.amd.rdna4 import ins as r4
    from tinygrad.runtime.autogen.amd.rdna3 import ins as r3
    out = {}
    for arch, mod in [("rdna4", r4), ("rdna3", r3)]:
        src = open(f"{TINYGRAD}/tinygrad/runtime/autogen/amd/{arch}/ins.py").read()
        classes = {}
        for m in re.finditer(r'class (\w+)\(Inst\):\s*\n\s*encoding = FixedBitField\((\d+), (\d+), (?:0b([01]+)|(\d+))\)\s*\n\s*op = EnumBitField\((\d+), (\d+), (\w+)', src):
            cls, ehi, elo, bval, dval, ohi, olo, ename = m.groups()
            enc_val = int(bval, 2) if bval else int(dval)
            enum_mod = getattr(__import__(f"tinygrad.runtime.autogen.amd.{arch}.enum", fromlist=[ename]), ename)
            ops = {x.value: x.name for x in enum_mod}
            classes[cls] = {"enc_hi": int(ehi), "enc_lo": int(elo), "enc_val": enc_val,
                            "op_hi": int(ohi), "op_lo": int(olo), "ops": ops}
        out[arch] = classes
    return out

def disasm(words, mcpu):
    b = []
    for w in words:
        b += [f"0x{w & 0xFF:02X}", f"0x{(w >> 8) & 0xFF:02X}", f"0x{(w >> 16) & 0xFF:02X}", f"0x{(w >> 24) & 0xFF:02X}"]
    r = subprocess.run([LLVM_MC, "-triple=amdgcn", f"-mcpu={mcpu}", "--disassemble"],
                       input=", ".join(b), capture_output=True, text=True)
    return r.stdout.strip() or "ENCODE-ERROR"

NAME_DIFF = {
    "GLOBAL_LOAD_DWORD": "GLOBAL_LOAD_B32", "GLOBAL_STORE_DWORD": "GLOBAL_STORE_B32",
    "GLOBAL_LOAD_DWORDX2": "GLOBAL_LOAD_B64", "GLOBAL_STORE_DWORDX2": "GLOBAL_STORE_B64",
    "GLOBAL_LOAD_DWORDX4": "GLOBAL_LOAD_B128", "GLOBAL_STORE_DWORDX4": "GLOBAL_STORE_B128",
    "S_LOAD_DWORD": "S_LOAD_B32", "S_LOAD_DWORDX2": "S_LOAD_B64", "S_LOAD_DWORDX4": "S_LOAD_B128",
    "V_ADD_CO_U32": "V_ADD_CO_U32", "V_SUB_CO_U32": "V_SUB_CO_U32",
    "V_ADD_CO_CI_U32": "V_ADD_CO_CI_U32", "V_SUB_CO_CI_U32": "V_SUB_CO_CI_U32",
}
GFX1100_MAP = {"GLOBAL_LOAD": "FLAT_LOAD", "GLOBAL_STORE": "FLAT_STORE",
               "GLOBAL_ATOMIC": "FLAT_ATOMIC"}

def main():
    tables = load_tables()
    gen = open(f"{REPO}/tests/encoding_golden_gen.rs").read()
    entries = []
    for ln in open("/tmp/enc_words.txt").read().strip().split("\n"):
        n, h = ln.split("|")
        entries.append((n, [int(x, 16) for x in h.split(",")]))
    match, namediff, unmatch = [], [], []
    for name, words in entries:
        mcpu = "gfx1200"
        d = disasm(words, mcpu)
        if "ENCODE-ERROR" in d:
            d = disasm(words, "gfx1100"); mcpu = "gfx1100"
            if "ENCODE-ERROR" in d: continue
        arch = "rdna4" if mcpu == "gfx1200" else "rdna3"
        mnem = re.sub(r"_e64$|_e32$", "", d.strip().split()[0]).upper()
        if mnem.startswith("V_DUAL"):
            from tinygrad.runtime.autogen.amd.rdna4.enum import VOPDOp
            opx, opy = (words[0] >> 22) & 0xF, (words[0] >> 17) & 0x1F
            nx, ny = VOPDOp(opx).name, VOPDOp(opy).name
            want = mnem.replace("V_DUAL_", "").split("_")
            ok = (nx == f"V_DUAL_{want[0]}" and ny == f"V_DUAL_{want[1]}")
            (match if ok else namediff).append((name, f"VOPD {nx}/{ny}"))
            continue
        cands = []
        for cls, t in tables[arch].items():
            width = t["enc_hi"] - t["enc_lo"] + 1
            got = (words[0] >> t["enc_lo"]) & ((1 << width) - 1)
            if got == t["enc_val"]:
                cands.append((t["enc_lo"], cls, t))
        if not cands:
            unmatch.append((name, f"{arch} 无前缀匹配")); continue
        cands.sort(key=lambda x: x[0])
        resolved = None
        for _, cls, t in cands:
            opval = (words[0] >> t["op_lo"]) & ((1 << (t["op_hi"] - t["op_lo"] + 1)) - 1)
            official = t["ops"].get(opval)
            if official is not None:
                resolved = (cls, official, opval); break
        if resolved is None:
            unmatch.append((name, f"op 表全未命中 (word0={words[0]:08X})")); continue
        cls, official, opval = resolved
        want = mnem
        for pat, rep in GFX1100_MAP.items():
            if want.startswith(pat) and mcpu == "gfx1100":
                want = rep + want[len(pat):]
        want = NAME_DIFF.get(want, want)
        off = re.sub(r"_E32$|_E64$", "", official.upper())
        if want == off or want.startswith(off) or off.startswith(want):
            match.append((name, f"{cls}.{official}"))
        else:
            namediff.append((name, f"llvm-mc={mnem} 官方={cls}.{official} (op={opval})"))
    print(f"官方 ISA XML 审计: 语义匹配 {len(match)} | 名差(人工核) {len(namediff)} | 不一致 {len(unmatch)}")
    for k, e in namediff: print(f"  [NAME-DIFF] {k}: {e}")
    for k, e in unmatch: print(f"  [UNMATCH] {k}: {e}")
    return len(unmatch)

if __name__ == "__main__":
    sys.exit(0 if main() == 0 else 1)
